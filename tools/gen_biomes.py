#!/usr/bin/env python3
"""T-006: biomes/registry.json -> datapack biome JSONs, resource-pack sound slots, paint spec, fade functions.
Outputs (all generated, do not edit by hand):
  datapack/data/last_ember/worldgen/biome/<id>.json
  datapack/data/last_ember/function/biomes/gen/fade_<chapter>.mcfunction   (fillbiome ... replace, tiled to <= 32768 blocks)
  biomes/paint.gen.json                                                    (read by tools/seedmap/BiomePaint.java)
  resourcepack/assets/last_ember/sounds.json  (via tools/gen_sounds.py: music slots + creature + sfx)
Usage: python3 tools/gen_biomes.py
"""
import sys, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
reg = json.load(open(os.path.join(ROOT, "biomes/registry.json"), encoding="utf-8"))
OUT = os.path.join(ROOT, "datapack/data/last_ember")
CATS = ["monster", "creature", "ambient", "axolotls", "underground_water_creature", "water_creature", "water_ambient", "misc"]

def dump(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f: json.dump(obj, f, indent=2, ensure_ascii=False); f.write("\n")

def spawns(b):
    s = b.get("spawns", {})
    cats = {c: [] for c in CATS}
    if s != "none":
        for c, lst in s.items():
            cats[c] = [{"type": f"minecraft:{t}", "weight": w, "count": n} for t, w, n in lst]
    return {"argument": {"spawn_costs": {}, "spawns_by_category": cats}, "modifier": "overlay"}

def biome(bid, b):
    a = {
        "minecraft:visual/sky_color": b["sky"], "minecraft:visual/fog_color": b["fog"], "minecraft:visual/water_fog_color": b["water_fog"],
        "minecraft:gameplay/natural_mob_spawns": spawns(b),
        "minecraft:audio/background_music": {"default": {"sound": {"sound_id": f"last_ember:music.{b['music']}"}, "min_delay": 6000, "max_delay": 24000}},
    }
    if "fog_start" in b: a["minecraft:visual/fog_start_distance"] = float(b["fog_start"]); a["minecraft:visual/fog_end_distance"] = float(b["fog_end"])
    if "light_tint" in b: a["minecraft:visual/block_light_tint"] = b["light_tint"]
    if b.get("particles"):
        a["minecraft:visual/ambient_particles"] = {"argument": [{"particle": {"type": f"minecraft:{p}"}, "probability": pr} for p, pr in b["particles"]], "modifier": "append"}
    if b.get("mood"):
        a["minecraft:audio/ambient_sounds"] = {"mood": {"sound": b["mood"], "tick_delay": 6000, "block_search_extent": 8, "offset": 2.0}}
    if b.get("no_sleep"):
        a["minecraft:gameplay/bed_rule"] = {"can_set_spawn": "never", "can_sleep": "never", "error_message": {"translate": "block.minecraft.bed.no_sleep"}}
        a["minecraft:gameplay/straw_bed_rule"] = {"can_set_spawn": "never", "can_sleep": "never", "destroy_on_leave": True, "error_message": {"translate": "block.minecraft.bed.no_sleep"}}
    if b.get("surface_slime"): a["minecraft:gameplay/surface_slime_spawn_chance"] = 0.5
    cold = b.get("temp", 0.6) < 0.15
    return {"attributes": a, "carvers": [], "features": [], "downfall": 0.8, "temperature": b.get("temp", 0.6), "has_precipitation": True,
            "effects": {"grass_color": b["grass"], "foliage_color": b["foliage"], "dry_foliage_color": b["foliage"], "water_color": b["water"]}}

def tiles(x1, z1, x2, z2, y1, y2):
    """boxes of at most 32768 blocks (fillbiome limit) covering the rectangle x y z"""
    step = 32
    for x in range(x1, x2 + 1, step):
        for z in range(z1, z2 + 1, step):
            for y in range(y1, y2 + 1, step):
                yield x, y, z, min(x + step - 1, x2), min(y + step - 1, y2), min(z + step - 1, z2)

def main():
    for bid, b in reg["biomes"].items(): dump(os.path.join(OUT, f"worldgen/biome/{bid}.json"), biome(bid, b))
    # fade functions (T-006; T-023: fillbiome works only in loaded chunks, so each column tile is applied when its chunks are loaded)
    gdir = os.path.join(OUT, "function/biomes/gen"); os.makedirs(gdir, exist_ok=True); tdir = os.path.join(gdir, "t"); os.makedirs(tdir, exist_ok=True)
    for d in (gdir, tdir):
        for f in os.listdir(d):
            if f.endswith(".mcfunction"): os.remove(os.path.join(d, f))
    allsync = ["# generated by tools/gen_biomes.py: every second (biomes/loop): pending fades are applied tile by tile where the chunks are loaded"]
    for name, steps in reg["fade"].items():
        cols = {}                                   # (x1, z1, x2, z2) -> [(y1, y2, from, to)]
        for st in steps:
            y1, y2 = st.get("y", [-64, 319])
            for x1, z1, x2, z2 in st["rects"]:
                for t in tiles(x1, z1, x2, z2, y1, y2): cols.setdefault((t[0], t[2], t[3], t[5]), []).append((t[1], t[4], st["from"], st["to"]))
        sync = ["# generated: tiles of '%s' that differ from #fade_%s le.bio (1 faded, 0 not) and whose chunks are loaded are applied now" % (name, name),
                "scoreboard players set #bleft le.bio 0"]
        for k, ((x1, z1, x2, z2), ys) in enumerate(sorted(cols.items())):
            fw = ["fillbiome %d %d %d %d %d %d last_ember:%s replace last_ember:%s" % (x1, a, z1, x2, b, z2, to, fr) for a, b, fr, to in ys]
            bw = ["fillbiome %d %d %d %d %d %d last_ember:%s replace last_ember:%s" % (x1, a, z1, x2, b, z2, fr, to) for a, b, fr, to in ys]
            open(os.path.join(tdir, "%s_%d.mcfunction" % (name, k)), "w").write("\n".join(["# generated: tile %d of '%s' (faded when #fade_%s le.bio = 1, else back)" % (k, name, name)] +
                ["execute if score #fade_%s le.bio matches 1 run %s" % (name, c) for c in fw] + ["execute unless score #fade_%s le.bio matches 1 run %s" % (name, c) for c in bw] +
                ["scoreboard players operation #bt_%s_%d le.bio = #fade_%s le.bio" % (name, k, name)]) + "\n")
            loaded = " ".join("if loaded %d 0 %d" % (cx * 16, cz * 16) for cx in range(x1 // 16, x2 // 16 + 1) for cz in range(z1 // 16, z2 // 16 + 1))
            sync.append("execute unless score #bt_%s_%d le.bio = #fade_%s le.bio %s run function last_ember:biomes/gen/t/%s_%d" % (name, k, name, loaded, name, k))
            sync.append("execute unless score #bt_%s_%d le.bio = #fade_%s le.bio run scoreboard players add #bleft le.bio 1" % (name, k, name))
        sync.append("execute if score #bleft le.bio matches 0 run scoreboard players set #bpend_%s le.bio 0" % name)
        open(os.path.join(gdir, "sync_%s.mcfunction" % name), "w").write("\n".join(sync) + "\n")
        init = ["execute unless score #bt_%s_%d le.bio matches 0..1 run scoreboard players set #bt_%s_%d le.bio 0" % (name, k, name, k) for k in range(len(cols))]
        open(os.path.join(gdir, "init_%s.mcfunction" % name), "w").write("\n".join(["# generated: tiles start not faded", "execute unless score #fade_%s le.bio matches 0..1 run scoreboard players set #fade_%s le.bio 0" % (name, name)] + init) + "\n")
        for fn, v, what in (("fade", 1, "faded versions"), ("unfade", 0, "back to the living versions (test/admin)")):
            open(os.path.join(gdir, "%s_%s.mcfunction" % (fn, name)), "w", encoding="utf-8").write("\n".join([
                "# generated by tools/gen_biomes.py: chapter '%s' %s; fillbiome replace keeps the dithered borders. Tiles in unloaded chunks follow" % (name, what),
                "# when their chunks load (biomes/gen/sync every second): %d tiles" % len(cols),
                "scoreboard players set #fade_%s le.bio %d" % (name, v), "scoreboard players set #bpend_%s le.bio 1" % name,
                "function last_ember:biomes/gen/sync_%s" % name]) + "\n")
        allsync.append("execute if score #bpend_%s le.bio matches 1 run function last_ember:biomes/gen/sync_%s" % (name, name))
        print(f"fade_{name}: {len(cols)} tiles")
    open(os.path.join(gdir, "sync.mcfunction"), "w").write("\n".join(allsync) + "\n")
    open(os.path.join(gdir, "init.mcfunction"), "w").write("\n".join(["# generated: called from biomes/setup"] + ["function last_ember:biomes/gen/init_%s" % n for n in reg["fade"]]) + "\n")
    # paint spec for the offline painter
    layers = []
    for p in reg["paint"]:
        bid = p["id"] if ":" in p["id"] else f"last_ember:{p['id']}"
        layers.append({"biome": bid, "shape": p["shape"], "v": p["v"], "trans": p.get("trans", 0), "y": p.get("y", [-64, 319])})
    dump(os.path.join(ROOT, "biomes/paint.gen.json"), {"seed": 1013, "layers": layers})
    import subprocess; subprocess.run([sys.executable, os.path.join(ROOT, "tools/gen_sounds.py")], check=True)   # sounds.json is written by gen_sounds.py (T-018)
    print(f"{len(reg['biomes'])} biomes, {len(layers)} paint layers, {len(reg['slots'])} sound slots")

if __name__ == "__main__":
    main()
