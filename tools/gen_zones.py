#!/usr/bin/env python3
"""T-004: compile zones/zones.txt (+ optional extra zone files) into datapack functions with a spatial index.

Index: 64x64 cells per dimension. A zone is registered in every cell its bounding box (expanded by the largest margin)
touches. At runtime an entity computes its cell and runs only that cell's checks (macro dispatch), so cost per check does
not grow with the total number of zones. Three check variants with different margins:
  p  players   margin 5 (survival reach 4.5): in zone -> adventure; also sets flag tags le.zf.<flag>
  t  TNT etc.  margin 8 (TNT blast reach)    : primed TNT / TNT minecarts near a zone are defused
Usage: python3 tools/gen_zones.py [extra_zone_file ...]
"""
import os, sys, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "datapack/data/last_ember/function/zones/gen")
CELL, OFF = 64, 8192  # OFF keeps coordinates positive so truncation == floor
MARGIN = {"p": 5, "t": 8}
DIMS = {"overworld": "o", "the_nether": "n", "the_end": "e"}
FLAGS = {"no_spawn", "no_blink", "no_fire", "calm", "dungeon", "border", "no_chorus"}

def parse(path):
    zones = []
    for ln, line in enumerate(open(path, encoding="utf-8"), 1):
        line = line.split("#", 1)[0].strip()
        if not line: continue
        f = line.split()
        zid, dim, shape = f[0], f[1], f[2]
        if dim not in DIMS: raise SystemExit(f"{path}:{ln}: unknown dimension {dim}")
        n = {"box": 6, "cyl": 5}.get(shape)
        if n is None: raise SystemExit(f"{path}:{ln}: unknown shape {shape}")
        nums = [int(v) for v in f[3:3 + n]]
        flags = set(f[3 + n].split(",")) if len(f) > 3 + n else set()
        if flags - FLAGS: raise SystemExit(f"{path}:{ln}: unknown flags {flags - FLAGS}")
        if shape == "box":
            x1, y1, z1, x2, y2, z2 = nums
            nums = [min(x1, x2), min(y1, y2), min(z1, z2), max(x1, x2), max(y1, y2), max(z1, z2)]
        zones.append({"id": zid, "dim": DIMS[dim], "shape": shape, "v": nums, "flags": sorted(flags)})
    return zones

def bbox(z):
    if z["shape"] == "box": x1, y1, z1, x2, y2, z2 = z["v"]; return x1, z1, x2, z2
    cx, cz, r, _, _ = z["v"]; return cx - r, cz - r, cx + r, cz + r

def test(z, m):
    """execute-subcommand string that succeeds when @s is inside zone z expanded by m (run 'at @s')."""
    if z["shape"] == "box":
        x1, y1, z1, x2, y2, z2 = z["v"]
        return f"if entity @s[x={x1 - m},y={y1 - m},z={z1 - m},dx={x2 - x1 + 2 * m},dy={y2 - y1 + 2 * m},dz={z2 - z1 + 2 * m}]"
    cx, cz, r, y1, y2 = z["v"]
    return f"if entity @s[y={y1 - m},dy={y2 - y1 + 2 * m}] positioned {cx}.5 ~ {cz}.5 if entity @s[distance=..{r + m}]"

def main():
    zones = parse(os.path.join(ROOT, "zones/zones.txt"))
    if os.path.exists(os.path.join(ROOT, "zones/bonfires.gen.txt")): zones += parse(os.path.join(ROOT, "zones/bonfires.gen.txt"))
    if os.path.exists(os.path.join(ROOT, "zones/traders.gen.txt")): zones += parse(os.path.join(ROOT, "zones/traders.gen.txt"))
    if os.path.exists(os.path.join(ROOT, "zones/gates.gen.txt")): zones += parse(os.path.join(ROOT, "zones/gates.gen.txt"))
    for extra in sys.argv[1:]: zones += parse(extra)
    ids = [z["id"] for z in zones]
    if len(ids) != len(set(ids)): raise SystemExit("duplicate zone ids")
    cells = {}
    mm = max(MARGIN.values())
    for z in zones:
        x1, z1, x2, z2 = bbox(z)
        for cx in range((x1 - mm + OFF) // CELL, (x2 + mm + OFF) // CELL + 1):
            for cz in range((z1 - mm + OFF) // CELL, (z2 + mm + OFF) // CELL + 1):
                cells.setdefault(f"{z['dim']}{cx}_{cz}", []).append(z)
    if os.path.isdir(OUT): shutil.rmtree(OUT)
    for v in MARGIN: os.makedirs(os.path.join(OUT, v))
    for key, zs in cells.items():
        for v, m in MARGIN.items():
            lines = []
            for z in zs:
                t = test(z, m)
                lines.append(f"execute {t} run scoreboard players set #hit le.z 1")
                if v == "p":
                    for fl in z["flags"]: lines.append(f"execute {t} run tag @s add le.zf.{fl}")
            open(os.path.join(OUT, v, key + ".mcfunction"), "w").write(f"# generated by tools/gen_zones.py: cell {key}\n" + "\n".join(lines) + "\n")
    keys = ",".join(f"{k}:1b" for k in sorted(cells))
    open(os.path.join(OUT, "init.mcfunction"), "w").write(
        "# generated by tools/gen_zones.py: list of non-empty cells for the macro dispatcher\n"
        f"data modify storage last_ember:zones cells set value {{{keys}}}\n"
        f"data modify storage last_ember:zones count set value {len(zones)}\n")
    # no_spawn: periodic removal of monsters inside flagged zones (no drops: sent to the void)
    ns = [z for z in zones if "no_spawn" in z["flags"]]
    dimname = {v: k for k, v in DIMS.items()}
    with open(os.path.join(OUT, "nospawn.mcfunction"), "w") as f:
        f.write("# generated by tools/gen_zones.py: monsters in no_spawn zones are removed without drops\n")
        for z in ns:
            sel = "type=#last_ember:monsters,tag=!le.keep"
            if z["shape"] == "box":
                x1, y1, z1, x2, y2, z2 = z["v"]
                f.write(f"execute in minecraft:{dimname[z['dim']]} as @e[{sel},x={x1},y={y1},z={z1},dx={x2 - x1},dy={y2 - y1},dz={z2 - z1}] run function last_ember:zones/remove_mob\n")
            else:
                cx, cz, r, y1, y2 = z["v"]
                f.write(f"execute in minecraft:{dimname[z['dim']]} as @e[{sel},x={cx - r},y={y1},z={cz - r},dx={2 * r},dy={y2 - y1},dz={2 * r}] at @s positioned {cx}.5 ~ {cz}.5 if entity @s[distance=..{r}] run function last_ember:zones/remove_mob\n")
    print(f"{len(zones)} zones, {len(cells)} index cells, {len(ns)} no_spawn zones")

if __name__ == "__main__":
    main()
