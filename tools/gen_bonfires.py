#!/usr/bin/env python3
"""T-005: compile bonfires/bonfires.txt (or a given file) into
  datapack/data/last_ember/function/bonfire/gen/register.mcfunction  (idempotent: builds + registers missing bonfires on load)
  datapack/data/last_ember/function/bonfire/gen/start.mcfunction     (start bonfire index)
  zones/bonfires.gen.txt                                             (radius-6 adventure zones, read by gen_zones.py)
Usage: python3 tools/gen_bonfires.py [bonfire_file]   then  python3 tools/gen_zones.py
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIMS = {"overworld": 0, "the_nether": 1, "the_end": 2}
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "bonfires/bonfires.txt")
rows = []
for ln, line in enumerate(open(src, encoding="utf-8"), 1):
    line = line.split("#", 1)[0].strip()
    if not line: continue
    f = line.split()
    i, bid, dim, x, y, z, kind, region = int(f[0]), f[1], f[2], int(f[3]), int(f[4]), int(f[5]), f[6], f[7]
    if dim not in DIMS or kind not in ("main", "normal"): raise SystemExit(f"{src}:{ln}: bad dimension/kind")
    opts = f[8:]
    variant = next((o.split("=", 1)[1] for o in opts if o.startswith("variant=")), {"r0": "std", "r1": "dol", "r2": "dol", "r3": "snow", "r4": "desert", "r5": "ash", "r6": "ash"}.get(region, "std"))
    rows.append(dict(i=i, id=bid, dim=dim, d=DIMS[dim], x=x, y=y, z=z, kind=kind, region=region, start="start" in opts, variant=variant, r=4 if kind == "main" else 3))
if len({r["i"] for r in rows}) != len(rows) or len({r["id"] for r in rows}) != len(rows): raise SystemExit("duplicate number or id")
starts = [r for r in rows if r["start"]]
if len(starts) > 1: raise SystemExit("more than one start bonfire")
out = os.path.join(ROOT, "datapack/data/last_ember/function/bonfire/gen"); os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "register.mcfunction"), "w") as f:
    f.write(f"# generated by tools/gen_bonfires.py from {os.path.relpath(src, ROOT)}\n")
    for r in rows:
        lit = 1 if r["kind"] == "main" else 0
        f.write(f'function last_ember:bonfire/place {{i:{r["i"]},id:"{r["id"]}",dim:"minecraft:{r["dim"]}",d:{r["d"]},x:{r["x"]},y:{r["y"]},z:{r["z"]},'
                f'rx:{r["x"]},ry:{r["y"]},rz:{r["z"] + r["r"] + 2},kind:"{r["kind"]}",region:"{r["region"]}",eternal:{lit},lit:{lit},variant:"{r["variant"]}",r:{r["r"]}}}\n')
with open(os.path.join(out, "build_pending.mcfunction"), "w") as f:
    f.write("# generated: registered but not yet built bonfires are built once their chunk is loaded (checked every second)\n")
    for r in rows:
        f.write(f'execute if data storage last_ember:bonfires by.b{r["i"]}{{built:0b}} in minecraft:{r["dim"]} if loaded {r["x"]} {r["y"]} {r["z"]} positioned {r["x"]} {r["y"]} {r["z"]} run function last_ember:bonfire/build_now {{i:{r["i"]}}}\n')
with open(os.path.join(out, "start.mcfunction"), "w") as f:
    f.write("# generated: index of the start bonfire (-1 = none)\n")
    f.write(f"scoreboard players set #start le.e {starts[0]['i'] if starts else -1}\n")
with open(os.path.join(ROOT, "zones/bonfires.gen.txt"), "w") as f:
    f.write("# generated by tools/gen_bonfires.py: every bonfire is an adventure zone of radius 6\n")
    for r in rows: f.write(f"bonfire_{r['id']} {r['dim']} cyl {r['x']} {r['z']} 6 {r['y'] - 3} {r['y'] + 6}\n")
print(f"{len(rows)} bonfires, start: {starts[0]['id'] if starts else 'none'}")
