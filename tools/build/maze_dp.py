import math, os, subprocess
from collections import deque
import numpy as np
import maze_layout as ML

def run(R, cells):
    G, Y, CEIL, CS = R.G, R.Y, R.CEIL, R.CS
    DP = R.DP; GEN = os.path.join(DP, "function/maze/gen"); STR = os.path.join(DP, "structure/maze")
    for d in (GEN, STR):
        os.makedirs(d, exist_ok=True)
        for root, _, fs in os.walk(d):
            for f in fs:
                if f.endswith(".mcfunction") or f.endswith(".nbt"): os.remove(os.path.join(root, f))
    os.makedirs(os.path.join(GEN, "c"), exist_ok=True); os.makedirs(os.path.join(GEN, "s"), exist_ok=True); os.makedirs(os.path.join(GEN, "h"), exist_ok=True)
    hdr = "# generated by tools/build/r1_maze.py (maze_dp.py): "
    def w(name, lines): open(os.path.join(GEN, name + ".mcfunction"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    def nbt(name, cells_, origin):
        p = os.path.join(R.OUT, "tpl_maze_" + name + ".txt")
        with open(p, "w") as f:
            for (x, y, z), s in sorted(cells_.items()): f.write(f"{x} {y} {z} {s}\n")
        r = subprocess.run([os.path.join(R.ROOT, "tools/blockwriter.sh"), "nbt", p, str(origin[0]), str(origin[1]), str(origin[2]), os.path.join(STR, name + ".nbt")], capture_output=True, text=True)
        if r.returncode or "nbt:" not in r.stdout: raise SystemExit(r.stdout + r.stderr)
        return p

    # ------------------------------------------------ statues of the dead ends: ids, positions, nearest movable cell
    statues = []          # dict(id, cell, var (None = permanent), x, z, exit, near_k)
    mcent = [(R.cell_origin(c)[0] + CS / 2, R.cell_origin(c)[1] + CS / 2) for c in R.MOVABLE]
    for c in sorted(cells):
        vs = cells[c]
        for vi, v in enumerate(vs):
            if c not in R.MOVABLE and vi: continue
            ox, oz = R.cell_origin(c)
            for lx, lz, d in R.statues_of(c, v):
                x, z = ox + lx, oz + lz
                own = R.MOVABLE.index(c) if c in R.MOVABLE else -1
                ks = sorted([k for k in range(6) if k != own], key=lambda k: math.hypot(mcent[k][0] - x - 0.5, mcent[k][1] - z - 0.5))
                statues.append(dict(id=len(statues) + 1, cell=c, var=(vi + 1) if c in R.MOVABLE else None, x=x, z=z, exit=d, near=ks[0] + 1))
    # ------------------------------------------------ templates: movable cells, exit, guards
    probes = {}
    masks = {}
    for k, c in enumerate(R.MOVABLE, 1):
        ox, oz = R.cell_origin(c)
        for vi, v in enumerate(cells[c]):
            bl = R.cell_blocks(c, v)
            nbt("cell%d_v%d" % (k, vi + 1), {(ox + lx, G + ly, oz + lz): s for (lx, ly, lz), s in bl.items()}, (ox, G, oz))
            masks[(k, vi + 1)] = R.cell_mask(c, v)
        # probes: cells at the middle of the hedge (y G+4) whose hedge / path pattern tells the 3 variants apart
        best = None
        for lz in range(CS):
            for lx in range(CS):
                sig = tuple(bool(masks[(k, vv)][lz, lx]) for vv in (1, 2, 3))
                if len(set(sig)) < 2: continue
                if best is None: best = [(lx, lz, sig)]
                elif all(s[2] != sig for s in best) and len(best) < 2: best.append((lx, lz, sig))
        # combine two probes so that every variant has its own signature
        found = None
        pos = [(lx, lz) for lz in range(CS) for lx in range(CS)]
        sigs = {p: tuple(bool(masks[(k, vv)][p[1], p[0]]) for vv in (1, 2, 3)) for p in pos}
        cand = [p for p in pos if len(set(sigs[p])) == 2]
        for i, p in enumerate(cand):
            for q in cand[i + 1:]:
                comb = [(sigs[p][vv], sigs[q][vv]) for vv in range(3)]
                if len(set(comb)) == 3: found = (p, q); break
            if found: break
        assert found, "no probes for cell %d" % k
        probes[k] = found
    nbt("exit_closed", R.exit_cells(False), (R.EXIT_X[0], G, R.EXIT_Z[0])); nbt("exit_open", R.exit_cells(True), (R.EXIT_X[0], G, R.EXIT_Z[0]))
    GD = {}
    for name, d in R.GUARDS:
        x1, z1 = R.guard_box(d)
        nbt("guard_%s_statue" % name, R.guard_cells(d, True), (x1, Y, z1)); nbt("guard_%s_empty" % name, R.guard_cells(d, False), (x1, Y, z1))
        yaw = math.degrees(math.atan2(d[0], -d[1]))       # facing the centre: the direction -d
        yaw = {(0, -1): 0.0, (0, 1): 180.0, (1, 0): 90.0, (-1, 0): -90.0}[d]
        GD[name] = dict(x1=x1, z1=z1, d=d, yaw=yaw, cx=x1 + 1.0, cz=z1 + 1.0, probe=None)
        # probe: the head of the statue (back-left column, G+5)
        sc = R.guard_cells(d, True)
        GD[name]["probe"] = [p for p, s in sc.items() if p[1] == Y + 4 and "polished_andesite" in s and "stairs" not in s][0]

    # ------------------------------------------------ per movable cell: place, probe, busy, loaded, try, pend
    statics = "type=!minecraft:player,type=!minecraft:item,type=!minecraft:marker,type=!minecraft:interaction,type=!minecraft:item_display,type=!minecraft:block_display,type=!minecraft:text_display,type=!minecraft:area_effect_cloud,type=!minecraft:experience_orb"
    for k, c in enumerate(R.MOVABLE, 1):
        ox, oz = R.cell_origin(c)
        for v in (1, 2, 3):
            m = masks[(k, v)]
            sts = {(sx, sz) for sx, sz, d in R.statues_of(c, cells[c][v - 1])}
            walk = m.copy()
            for sx, sz in sts: walk[sz, sx] = False
            others = np.zeros(m.shape, bool)
            for vv in (1, 2, 3):
                if vv != v: others |= masks[(k, vv)]
            moved = others & ~walk
            # nearest walkable cell of the new variant (BFS over the cell, 4-neighbourhood, through anything)
            dist = np.full(m.shape, 9999); tgt = {}
            dq = deque()
            for lz in range(CS):
                for lx in range(CS):
                    if walk[lz, lx]: dist[lz, lx] = 0; tgt[(lx, lz)] = (lx, lz); dq.append((lx, lz))
            while dq:
                lx, lz = dq.popleft()
                for dx, dz in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    q = (lx + dx, lz + dz)
                    if 0 <= q[0] < CS and 0 <= q[1] < CS and dist[q[1], q[0]] > dist[lz, lx] + 1:
                        dist[q[1], q[0]] = dist[lz, lx] + 1; tgt[q] = tgt[(lx, lz)]; dq.append(q)
            L = [hdr + "movable cell %d (%d,%d) -> variant %d: mobs on cells that become hedge or a statue go to the nearest path of the new variant, then the template" % (k, c[0], c[1], v)]
            # merge runs along x with the same target
            for lz in range(CS):
                lx = 0
                while lx < CS:
                    if not moved[lz, lx]: lx += 1; continue
                    t = tgt[(lx, lz)]; e = lx
                    while e + 1 < CS and moved[lz, e + 1] and tgt[(e + 1, lz)] == t: e += 1
                    L.append("execute as @e[%s,x=%d,y=%d,z=%d,dx=%d,dy=6,dz=0] run tp @s %.1f %d %.1f" % (statics, ox + lx, Y, oz + lz, e - lx, ox + t[0] + 0.5, Y, oz + t[1] + 0.5))
                    lx = e + 1
            # plants of the old variant go first (set to air, no drops): a flower left over a path block that changes pops as an item
            L.append("fill %d %d %d %d %d %d minecraft:air replace #minecraft:small_flowers" % (ox, Y, oz, ox + CS - 1, Y, oz + CS - 1))
            L.append("fill %d %d %d %d %d %d minecraft:air replace minecraft:wildflowers" % (ox, Y, oz, ox + CS - 1, Y, oz + CS - 1))
            L.append("fill %d %d %d %d %d %d minecraft:air replace minecraft:moss_carpet" % (ox, Y, oz, ox + CS - 1, Y, oz + CS - 1))
            L.append("place template last_ember:maze/cell%d_v%d %d %d %d" % (k, v, ox, G, oz))
            L.append("scoreboard players set #v%d le.mz %d" % (k, v))
            L.append("data modify storage last_ember:maze v.c%d set value %d" % (k, v))
            for s in statues:
                if s["cell"] == c: L += ["scoreboard players set #n%d le.mz 0" % s["id"], "scoreboard players set #h%d le.mz 0" % s["id"]]
            w("place_%d_%d" % (k, v), L)
        (p1, p2) = probes[k]
        L = [hdr + "the variant of cell %d standing in the world (1..3), 0 = none of them (not built yet)" % k]
        for v in (1, 2, 3):
            conds = []
            for p in (p1, p2):
                path = bool(masks[(k, v)][p[1], p[0]])
                conds.append(("if" if path else "unless") + " block %d %d %d minecraft:air" % (ox + p[0], G + 4, oz + p[1]))
            L.append("execute %s run return %d" % (" ".join(conds), v))
        L.append("return 0"); w("probe_%d" % k, L)
        X1, Z1 = ox - 2, oz - 2
        box = "x=%d,y=%d,z=%d,dx=27,dy=12,dz=27" % (X1, G - 2, Z1)
        w("busy_%d" % k, [hdr + "1 when somebody / something is in cell %d or within 2 blocks of it: a player (not spectator), an ash trail, an item, a trader or an npc" % k,
                          "execute if entity @a[%s,gamemode=!spectator] run return 1" % box,
                          "execute if entity @e[type=minecraft:interaction,tag=le.ashclick,%s] run return 1" % box,
                          "execute if entity @e[type=minecraft:item,%s] run return 1" % box,
                          "execute if entity @e[tag=le.npc,%s] run return 1" % box,
                          "execute if entity @e[tag=le.trader,%s] run return 1" % box,
                          "return 0"])
        w("loaded_%d" % k, [hdr + "1 when the chunks of cell %d are loaded" % k] +
          ["execute unless loaded %d %d %d run return 0" % (x, G, z) for x in (ox, ox + CS - 1) for z in (oz, oz + CS - 1)] + ["return 1"])
        w("try_%d" % k, [hdr + "rebuild cell %d into another variant (after 1 s of rustling) when it is free; 1 = started" % k,
                         "execute if score #pv%d le.mz matches 1.. run return 0" % k,
                         "execute unless function last_ember:maze/gen/loaded_%d run return 0" % k,
                         "execute if function last_ember:maze/gen/busy_%d run return 0" % k,
                         "execute store result score #r le.mz run random value 1..2",
                         "scoreboard players operation #pv%d le.mz = #v%d le.mz" % (k, k),
                         "scoreboard players operation #pv%d le.mz += #r le.mz" % k,
                         "execute if score #pv%d le.mz matches 4.. run scoreboard players remove #pv%d le.mz 3" % (k, k),
                         "scoreboard players set #pt%d le.mz 20" % k,
                         "playsound minecraft:block.poplar_leaves.ambient block @a %d %d %d 1 0.7" % (ox + 12, Y + 3, oz + 12),
                         "playsound minecraft:block.azalea_leaves.step block @a %d %d %d 1 0.6" % (ox + 12, Y + 3, oz + 12),
                         "return 1"])
        w("pend_%d" % k, [hdr + "every 5 ticks while cell %d waits for its rebuild: leaves fall, then the template (if it is still free)" % k,
                          "scoreboard players remove #pt%d le.mz 5" % k,
                          "particle minecraft:red_poplar_leaves %d %d %d 7 1.5 7 0 14 normal" % (ox + 12, CEIL - 2, oz + 12),
                          "particle minecraft:orange_poplar_leaves %d %d %d 7 1.5 7 0 10 normal" % (ox + 12, CEIL - 2, oz + 12),
                          "execute if score #pt%d le.mz matches 1.. run return 0" % k,
                          "execute if function last_ember:maze/gen/busy_%d run return run scoreboard players set #pv%d le.mz 0" % (k, k),
                          "execute if score #pv%d le.mz matches 1 run function last_ember:maze/gen/place_%d_1" % (k, k),
                          "execute if score #pv%d le.mz matches 2 run function last_ember:maze/gen/place_%d_2" % (k, k),
                          "execute if score #pv%d le.mz matches 3 run function last_ember:maze/gen/place_%d_3" % (k, k),
                          "scoreboard players set #pv%d le.mz 0" % k, "scoreboard players add #rebuilds le.mz 1"])
    w("pend", [hdr + "every 5 ticks: the pending rebuilds"] + ["execute if score #pv%d le.mz matches 1.. run function last_ember:maze/gen/pend_%d" % (k, k) for k in range(1, 7)])
    # sync: the variants, the exit, the guards (every second, where loaded, never during a pending rebuild)
    S = [hdr + "every second: what stands in the world follows the state (variants of the movable cells, the exit, the guards)"]
    for k in range(1, 7):
        S.append("execute if score #pv%d le.mz matches 0 if function last_ember:maze/gen/loaded_%d run function last_ember:maze/gen/sync_%d" % (k, k, k))
        w("sync_%d" % k, [hdr + "cell %d: the wanted variant differs from what stands -> place it when the cell is free" % k,
                          "execute store result score #pr le.mz run function last_ember:maze/gen/probe_%d" % k,
                          "execute if score #pr le.mz = #v%d le.mz run return 0" % k,
                          "execute if score #pr le.mz matches 1.. if function last_ember:maze/gen/busy_%d run return 0" % k] +
          ["execute if score #v%d le.mz matches %d run function last_ember:maze/gen/place_%d_%d" % (k, v, k, v) for v in (1, 2, 3)])
    ex = (-151, G + 4, -466)
    S.append("execute if loaded %d %d %d if loaded %d %d %d run function last_ember:maze/gen/sync_exit" % (R.EXIT_X[0], G, R.EXIT_Z[0], R.EXIT_X[1], G, R.EXIT_Z[1]))
    w("sync_exit", [hdr + "the secret exit: open (air in the corridor) / closed (hedge)",
                    "execute if score #exit le.mz matches 1 if block %d %d %d minecraft:air run return 0" % ex,
                    "execute if score #exit le.mz matches 0 unless block %d %d %d minecraft:air run return 0" % ex,
                    "execute if score #exit le.mz matches 1 run return run place template last_ember:maze/exit_open %d %d %d" % (R.EXIT_X[0], G, R.EXIT_Z[0]),
                    "place template last_ember:maze/exit_closed %d %d %d" % (R.EXIT_X[0], G, R.EXIT_Z[0])])
    for name, g in GD.items():
        px, py, pz = g["probe"]
        S.append("execute if loaded %d %d %d run function last_ember:maze/gen/sync_g_%s" % (g["x1"], Y, g["z1"], name))
        w("sync_g_%s" % name, [hdr + "guard %s: stone (0) = the statue on the pedestal; waking/alive/killed = the empty pedestal" % name,
                               "execute if score #g_%s le.mz matches 0 unless block %d %d %d minecraft:polished_andesite run place template last_ember:maze/guard_%s_statue %d %d %d" % (name, px, py, pz, name, g["x1"], Y, g["z1"]),
                               "execute if score #g_%s le.mz matches 1..2 if block %d %d %d minecraft:polished_andesite run place template last_ember:maze/guard_%s_empty %d %d %d" % (name, px, py, pz, name, g["x1"], Y, g["z1"])])
    w("sync", S)
    # rounds of the shuffle: start at a random cell, try the cells in order until #want are started
    for r in range(6):
        L = [hdr + "shuffle round from cell %d: up to #want rebuilds" % (r + 1)]
        for i in range(6):
            k = (r + i) % 6 + 1
            L.append("execute if score #want le.mz matches 1.. if function last_ember:maze/gen/try_%d run scoreboard players remove #want le.mz 1" % k)
        w("round_%d" % (r + 1), L)
    w("round", [hdr + "macro-free dispatch of the shuffle round (#r = 1..6)"] + ["execute if score #r le.mz matches %d run function last_ember:maze/gen/round_%d" % (r, r) for r in range(1, 7)])
    w("set", [hdr + "maze/set: #cell (1..6) to variant #var (1..3), now (admin, the cell is placed even when somebody stands in it)"] +
      ["execute if score #cell le.mz matches %d if score #var le.mz matches %d run function last_ember:maze/gen/place_%d_%d" % (k, v, k, v) for k in range(1, 7) for v in (1, 2, 3)])
    w("try_dispatch", [hdr + "#cell -> try_<cell>, result in #ok"] + ["execute if score #cell le.mz matches %d store result score #ok le.mz run function last_ember:maze/gen/try_%d" % (k, k) for k in range(1, 7)])

    # ------------------------------------------------ the player's cell and its statues
    L = [hdr + "as a player in the maze: #cx #cz (0..4) -> the statues of that cell (movable cells: of the variant that stands)"]
    for c in sorted(cells):
        if c == ML.SANCTUM: continue
        L.append("execute if score #cx le.mz matches %d if score #cz le.mz matches %d run return run function last_ember:maze/gen/c/%d_%d" % (c[0], c[1], c[0], c[1]))
        if c in R.MOVABLE:
            k = R.MOVABLE.index(c) + 1
            w("c/%d_%d" % c, ["# generated: cell %d,%d (movable %d): by the variant" % (c[0], c[1], k)] +
              ["execute if score #v%d le.mz matches %d run return run function last_ember:maze/gen/c/%d_%d_%d" % (k, v, c[0], c[1], v) for v in (1, 2, 3)])
    w("pc", L)
    SH = (0.5, 3.5, 0.5)
    groups = {}
    for s in statues:
        key = "%d_%d" % s["cell"] + ("_%d" % s["var"] if s["var"] else "")
        groups.setdefault(key, []).append(s)
    for c in sorted(cells):
        if c == ML.SANCTUM: continue
        keys = ["%d_%d_%d" % (c[0], c[1], v) for v in (1, 2, 3)] if c in R.MOVABLE else ["%d_%d" % c]
        for key in keys:
            L = ["# generated: the dead-end statues of this cell: within 4 blocks -> near (head follows later), looked at -> gaze"]
            for s in groups.get(key, []):
                L.append("execute positioned %.1f %d %.1f if entity @s[distance=..4] run function last_ember:maze/gen/s/%d" % (s["x"] + 0.5, Y, s["z"] + 0.5, s["id"]))
            w("c/" + key, L)
    for s in statues:
        i = s["id"]; hx, hy, hz = s["x"] + 0.5, Y + 2.5, s["z"] + 0.5
        w("s/%d" % i, ["# generated: statue %d at %d %d (cell %d,%d%s), exit %s, nearest movable cell %d" % (i, s["x"], s["z"], s["cell"][0], s["cell"][1], (" v%d" % s["var"]) if s["var"] else "", s["exit"], s["near"]),
                       "scoreboard players set #n%d le.mz 1" % i,
                       "execute at @s anchored eyes facing %.1f %.1f %.1f anchored feet positioned ^ ^ ^1 rotated as @s positioned ^ ^ ^-1 if entity @s[distance=..0.35] run function last_ember:maze/gen/s/l%d" % (hx, hy, hz, i)])
        w("s/l%d" % i, ["# generated: the player looks at statue %d (within 20 degrees)" % i, "tag @s add le.mzlook",
                        "execute unless score @s le.mzs matches %d run scoreboard players set @s le.mzg 0" % i,
                        "scoreboard players set @s le.mzs %d" % i, "scoreboard players add @s le.mzg 5",
                        "execute if score @s le.mzg matches 20.. run function last_ember:maze/gen/s/f%d" % i])
        w("s/f%d" % i, ["# generated: one second of the look at statue %d: the nearest movable cell (%d) rebuilds, cooldowns 20 s here and 5 s for the maze" % (i, s["near"]),
                        "scoreboard players set @s le.mzg 0",
                        "execute if score #gt le.mz < #cd%d le.mz run return 0" % i, "execute if score #gt le.mz < #gcd le.mz run return 0",
                        "execute unless function last_ember:maze/gen/try_%d run return 0" % s["near"],
                        "scoreboard players operation #cd%d le.mz = #gt le.mz" % i, "scoreboard players add #cd%d le.mz 400" % i,
                        "scoreboard players operation #gcd le.mz = #gt le.mz", "scoreboard players add #gcd le.mz 100", "scoreboard players add #looks le.mz 1"])
        w("h/t%d" % i, ["# generated: statue %d: the head turns after the player (the face along the way out)" % i,
                        "setblock %d %d %d %s" % (s["x"], Y + 2, s["z"], R.head_state(s["exit"], True)),
                        "scoreboard players set #n%d le.mz 0" % i, "scoreboard players set #h%d le.mz 1" % i,
                        "scoreboard players operation #hr%d le.mz = #gt le.mz" % i, "scoreboard players add #hr%d le.mz 1200" % i])
        w("h/r%d" % i, ["# generated: statue %d: the head straight again" % i, "setblock %d %d %d %s" % (s["x"], Y + 2, s["z"], R.head_state(s["exit"], False)),
                        "scoreboard players set #h%d le.mz 0" % i])
    H = [hdr + "every 10 ticks: heads of the dead-end statues (follow a player who was within 4 and is now farther than 6; back after 60 s when nobody is within 16)"]
    for s in statues:
        i = s["id"]; pre = ""
        if s["var"]: pre = "if score #v%d le.mz matches %d " % (R.MOVABLE.index(s["cell"]) + 1, s["var"])
        H.append("execute %sif score #n%d le.mz matches 1 if loaded %d %d %d positioned %.1f %d %.1f unless entity @a[distance=..6,gamemode=!spectator] run function last_ember:maze/gen/h/t%d" % (pre, i, s["x"], Y, s["z"], s["x"] + 0.5, Y, s["z"] + 0.5, i))
        H.append("execute %sif score #h%d le.mz matches 1 if score #gt le.mz >= #hr%d le.mz if loaded %d %d %d positioned %.1f %d %.1f unless entity @a[distance=..16,gamemode=!spectator] run function last_ember:maze/gen/h/r%d" % (pre, i, i, s["x"], Y, s["z"], s["x"] + 0.5, Y, s["z"] + 0.5, i))
