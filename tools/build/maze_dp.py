    w("heads_all_rest", [hdr + "admin: every turned head straight again (where loaded)"] +
      ["execute if score #h%d le.mz matches 1 if loaded %d %d %d run function last_ember:maze/gen/h/r%d" % (s["id"], s["x"], Y, s["z"], s["id"]) for s in statues])
