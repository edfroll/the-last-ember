#!/usr/bin/env python3
"""Generates runtime build functions from the builder pieces: bonfire variants and urn variants (datapack/.../function/*/gen/)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bonfire_std, urn
from connect import connect
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
F = os.path.join(ROOT, "datapack/data/last_ember/function")
for v in bonfire_std.VARIANTS:
    for r in (3, 4):
        b = bonfire_std.build(v, r); connect(b)
        b.write_mcfunction(os.path.join(F, f"bonfire/gen/build_{v}_r{r}.mcfunction"), 0, 0, 0, f"# generated by tools/build/gen_runtime.py: bonfire '{v}', circle {2*r+1}x{2*r+1}, at the hearth")
for r in (3, 4):
    lines = [f"# generated: lit state of a bonfire with circle radius {r} (at the hearth)",
             "execute if block ~ ~-1 ~ minecraft:hay_block run setblock ~ ~ ~ minecraft:campfire[lit=true,signal_fire=true]",
             "execute unless block ~ ~-1 ~ minecraft:hay_block run setblock ~ ~ ~ minecraft:campfire[lit=true,signal_fire=false]",
             f"setblock ~ ~1 ~-{r} minecraft:shroomlight"]
    lines += [f"setblock ~{dx} ~ ~{dz} minecraft:candle[candles=3,lit=true]" for dx, dz in ((-r, -r), (r, -r), (-r, r), (r, r))]
    open(os.path.join(F, f"bonfire/gen/lit_r{r}.mcfunction"), "w").write("\n".join(lines) + "\n")
for v in urn.VARIANTS:
    b = urn.build(v); connect(b)
    b.write_mcfunction(os.path.join(F, f"urn/gen/build_{v}.mcfunction"), 0, 0, 0, f"# generated by tools/build/gen_runtime.py: urn '{v}' at the anchor (podium centre, square level)")
print("runtime pieces generated")
