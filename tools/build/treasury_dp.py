def T(text, **kw):
    for k, v in kw.items(): text = text.replace("«%s»" % k, str(v))
    assert "«" not in text, text[text.index("«"):text.index("«") + 30]
    return text


def write(sub, name, doc, body, **kw):
    p = os.path.join(GEN, sub, name + ".mcfunction")
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(HDR + doc + "\n" + T(body.strip("\n"), **kw) + "\n")


def adv(name, trigger, cond, reward):
    p = os.path.join(DP, "advancement/treasury", name + ".json")
    os.makedirs(os.path.dirname(p), exist_ok=True)
    json.dump({"criteria": {"c": {"trigger": trigger, "conditions": cond}}, "rewards": {"function": reward}}, open(p, "w"), indent=1)


def clean(sub):
    d = os.path.join(GEN, sub)
    if os.path.isdir(d):
        for f in os.listdir(d):
            if f.endswith(".mcfunction"): os.remove(os.path.join(d, f))


def f2(v): return ("%.2f" % v).rstrip("0").rstrip(".") if isinstance(v, float) and v != int(v) else ("%d.0" % v if float(v) == int(v) else str(v))
def box_sel(b, pad=0):
    """x1 y1 z1 x2 y2 z2 (inclusive blocks) -> a selector part"""
    x1, y1, z1, x2, y2, z2 = b
    return "x=%d,y=%d,z=%d,dx=%d,dy=%d,dz=%d" % (x1 - pad, y1 - pad, z1 - pad, x2 - x1 + 2 * pad, y2 - y1 + 2 * pad, z2 - z1 + 2 * pad)
