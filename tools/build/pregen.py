#!/usr/bin/env python3
"""Generate world chunks over rectangles through the running test server (forceload in blocks of 16x16 chunks).
Usage: python3 tools/build/pregen.py x1 z1 x2 z2 [x1 z1 x2 z2 ...]   (block coordinates, inclusive)
Chunks are generated by forceload, the block is released once every chunk reports loaded; save-all at the end."""
import os, sys, time, importlib.util
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sp = importlib.util.spec_from_file_location("rcon", os.path.join(ROOT, "tools/rcon.py")); rc = importlib.util.module_from_spec(sp); sp.loader.exec_module(rc)
def chunks(a):
    out = []
    for i in range(0, len(a), 4):
        x1, z1, x2, z2 = a[i:i + 4]
        for cz in range(min(z1, z2) >> 4, (max(z1, z2) >> 4) + 1):
            for cx in range(min(x1, x2) >> 4, (max(x1, x2) >> 4) + 1): out.append((cx, cz))
    return sorted(set(out), key=lambda c: (c[1] >> 4, c[0] >> 4, c[1], c[0]))
def main():
    a = list(map(int, sys.argv[1:])); cs = chunks(a); blocks = {}
    for c in cs: blocks.setdefault((c[0] >> 4, c[1] >> 4), []).append(c)
    t0 = time.time(); done = 0
    rc.run("forceload remove all")
    for k, (bk, lst) in enumerate(sorted(blocks.items(), key=lambda kv: (kv[0][1], kv[0][0]))):
        xs = [c[0] for c in lst]; zs = [c[1] for c in lst]
        rc.run(f"forceload add {min(xs) * 16} {min(zs) * 16} {max(xs) * 16 + 15} {max(zs) * 16 + 15}")
        pend = list(lst)
        while pend:
            time.sleep(0.5)
            pend = [c for c in pend if "passed" not in rc.run(f"execute if loaded {c[0] * 16} 0 {c[1] * 16}")]
        rc.run("forceload remove all"); done += len(lst)
        el = time.time() - t0
        print(f"block {k + 1}/{len(blocks)}: {done}/{len(cs)} chunks, {done / el:.1f}/s, eta {(len(cs) - done) / max(done / el, 0.1) / 60:.1f} min", flush=True)
    rc.run("save-all flush"); print(f"done: {len(cs)} chunks in {(time.time() - t0) / 60:.1f} min")
if __name__ == "__main__": main()
