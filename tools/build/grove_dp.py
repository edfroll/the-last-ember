def circle_point(root):
    """the point of T-023 (the markers of the Circle write it into the storage): read from the generated function, never guessed"""
    import re
    t = open(os.path.join(root, "datapack/data/last_ember/function/weepers/gen/markers.mcfunction"), encoding="utf-8").read()
    m = re.search(r"m\.weepers_advisor set value \{pos:\[(-?\d+),(-?\d+),(-?\d+)\],yaw:(-?[\d.]+)f\}", t)
    return (int(m.group(1)), int(m.group(2)), int(m.group(3)), float(m.group(4)))

