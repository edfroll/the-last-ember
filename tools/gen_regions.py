#!/usr/bin/env python3
"""T-023: the fade of the regions at the end of a chapter (one module for every chapter): regions/fade.txt + bonfires/bonfires.txt ->
  datapack/data/last_ember/function/region/gen/chapter_<N>   called from altar/hook/chapter_<N> (all six exist, empty when nothing fades)
  datapack/data/last_ember/function/region/gen/fade_<r>      the faded versions of the biomes, the bonfires of the region go out, the message,
                                                             the hooks of the places region/hook/fade_<r>_<place>
  datapack/data/last_ember/function/region/gen/unfade_<r>    back (test/admin: altar/reset {chapter:N}): biomes back, faded bonfires lit again,
                                                             hooks region/hook/unfade_<r>_<place>
  datapack/data/last_ember/function/region/hook/*            stubs, written only when missing (the tasks of the places fill them)
A faded bonfire: state 0 + faded:1b + lv:1b in its storage (lv = the look it shows): bonfire/gen/build_pending makes it look out when its
chunk is loaded. The players bound to it keep their respawn point; it cannot be bound again (rest) nor bless a knight until the Ember
carrier lights it again (the usual click: bonfire/light).
Usage: python3 tools/gen_regions.py"""
import os, re, shlex
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
F = os.path.join(ROOT, "datapack/data/last_ember/function/region"); GEN = os.path.join(F, "gen"); HOOK = os.path.join(F, "hook")
for d in (GEN, HOOK): os.makedirs(d, exist_ok=True)
for f in os.listdir(GEN):
    if f.endswith(".mcfunction"): os.remove(os.path.join(GEN, f))
def w(path, lines): open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
bonf = []
for line in open(os.path.join(ROOT, "bonfires/bonfires.txt"), encoding="utf-8"):
    a = line.split("#", 1)[0].split()
    if a: bonf.append(dict(i=int(a[0]), id=a[1], kind=a[6], region=a[7], nofade="nofade" in a[8:]))
regs = []
for line in open(os.path.join(ROOT, "regions/fade.txt"), encoding="utf-8"):
    if not line.split("#", 1)[0].strip(): continue
    a = shlex.split(line.split(" #", 1)[0]); kv = dict(t.split("=", 1) for t in a[2:])
    regs.append(dict(r=a[0], ch=int(a[1]), biomes=kv.get("biomes"), hooks=[h for h in kv.get("hooks", "").split(",") if h], text=kv.get("text")))
for ch in range(1, 7):
    w(os.path.join(GEN, "chapter_%d.mcfunction" % ch), ["# generated by tools/gen_regions.py: the regions that fade at the end of the chapter %d" % ch] +
      ["function last_ember:region/gen/fade_%s" % g["r"] for g in regs if g["ch"] == ch])
for g in regs:
    r = g["r"]; num = int(re.sub(r"\D", "", r)); fb = [b for b in bonf if b["region"] == r and b["kind"] == "normal" and not b["nofade"]]
    L = ["# generated by tools/gen_regions.py: the region %s fades (end of the chapter %d); a repeat does nothing" % (r, g["ch"]),
         "execute if score #fade_%s le.alt matches 1 run return 0" % r, "scoreboard players set #fade_%s le.alt 1" % r]
    if g["biomes"]: L.append("function last_ember:biomes/gen/fade_%s" % g["biomes"])
    L.append("# bonfires go out: %s (kept: %s)" % (", ".join(str(b["i"]) for b in fb), ", ".join(str(b["i"]) for b in bonf if b["region"] == r and b not in fb) or "-"))
    L += ["execute if data storage last_ember:bonfires by.b%d{state:1} run data modify storage last_ember:bonfires by.b%d merge value {state:0,faded:1b,lv:1b}" % (b["i"], b["i"]) for b in fb]
    L.append("function last_ember:bonfire/gen/build_pending")
    if g["text"]:
        L.append('execute as @a at @s run function last_ember:elite/gen/region')
        L.append('execute as @a at @s run function last_ember:region/gen/msg_%s' % r)
        w(os.path.join(GEN, "msg_%s.mcfunction" % r), ["# generated: as a player: the message of the fade of %s when he is in the region" % r,
            "function last_ember:elite/gen/region", 'execute if score #rg le.el matches %d run title @s actionbar {"text":"%s","color":"gold"}' % (num, g["text"]),
            "execute if score #rg le.el matches %d run playsound minecraft:block.fire.extinguish ambient @s ~ ~ ~ 0.6 0.5" % num])
        L.pop(-2)
    L += ["function last_ember:region/hook/fade_%s_%s" % (r, h) for h in g["hooks"]]
    w(os.path.join(GEN, "fade_%s.mcfunction" % r), L)
    U = ["# generated by tools/gen_regions.py: TEST/ADMIN: the region %s back as before the fade (respawn points of the players are not touched)" % r,
         "scoreboard players set #fade_%s le.alt 0" % r]
    if g["biomes"]: U.append("function last_ember:biomes/gen/unfade_%s" % g["biomes"])
    U += ["execute if data storage last_ember:bonfires by.b%d{faded:1b} run data modify storage last_ember:bonfires by.b%d merge value {state:1,faded:0b,lv:0b}" % (b["i"], b["i"]) for b in fb]
    U.append("function last_ember:bonfire/gen/build_pending")
    U += ["function last_ember:region/hook/unfade_%s_%s" % (r, h) for h in g["hooks"]]
    w(os.path.join(GEN, "unfade_%s.mcfunction" % r), U)
    for h in g["hooks"]:
        for k, what in (("fade", "the faded version of the place"), ("unfade", "back to the living version (test/admin)")):
            p = os.path.join(HOOK, "%s_%s_%s.mcfunction" % (k, r, h))
            if not os.path.exists(p): w(p, ["# %s %s: %s (filled by the task of the place)" % (r, h, what)])
    print("%s: chapter %d, bonfires out %s, biomes %s, hooks %s" % (r, g["ch"], [b["i"] for b in fb], g["biomes"], g["hooks"]))
